"""Общие зависимости роутеров.

Аутентификации в системе нет (ответы экспертов, п. 21), но ЗАД.ФТ.12 и
ЭКС.ФТ.9 требуют показать в сообщении о конфликте, кто именно изменил запись.
Компромисс — заголовок ``X-User-Name``: фронтенд хранит введенное оператором
имя и шлет его с каждым изменяющим запросом. Никакой инфраструктуры
аутентификации это не добавляет, но сообщения о конфликте перестают быть
безличными.

ФИО кириллические, а значения HTTP-заголовков — не текст, а октеты, которые
каждый стек декодирует по-своему (Starlette — как latin-1, многие HTTP-клиенты
вообще отказываются отправлять не-ASCII). Поэтому принимаются оба варианта,
которые встречаются на практике:

* процентное кодирование UTF-8 (``%D0%98%D0%B2%D0%B0%D0%BD%D0%BE%D0%B2``) —
  то, что должен слать корректный клиент, и единственный способ пройти через
  строгий HTTP-клиент;
* сырые UTF-8-октеты, как их шлет браузер, — они доезжают «кракозябрами» после
  latin-1 и восстанавливаются обратным преобразованием.
"""

from __future__ import annotations

from typing import Annotated
from urllib.parse import unquote

from fastapi import Header

DEFAULT_USER = "Оператор"
MAX_USER_NAME_LENGTH = 200


def _repair_latin1(value: str) -> str:
    """Вернуть UTF-8-текст, приехавший октетами и раскодированный как latin-1.

    Для ASCII-строки преобразование тождественно, для уже корректной
    кириллицы ``encode('latin-1')`` падает — в обоих случаях значение
    возвращается как есть.
    """
    try:
        return value.encode("latin-1").decode("utf-8")
    except (UnicodeEncodeError, UnicodeDecodeError):
        return value


def current_user(x_user_name: Annotated[str | None, Header()] = None) -> str:
    if not x_user_name:
        return DEFAULT_USER
    name = _repair_latin1(unquote(_repair_latin1(x_user_name))).strip()
    # Имя попадает в сообщения и в журнал выгрузок — обрезаем, чтобы заголовок
    # не превращался в способ записать килобайт текста в каждую строку.
    return name[:MAX_USER_NAME_LENGTH] or DEFAULT_USER
